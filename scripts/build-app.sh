#!/bin/zsh
# Builds MacSpaceTidy.app (Apple silicon + Intel) into ./build with an ad-hoc signature.
# Needs only the Xcode command line tools.
set -euo pipefail

APP_NAME="MacSpaceTidy"
BUNDLE_ID="io.github.yanmasharski.MacSpaceTidy"
VERSION="0.3.0"
MIN_MACOS="14.0"

cd "$(dirname "$0")/.."
BUILD_ARGS=(-c release --arch arm64 --arch x86_64 --product MacSpaceTidyApp)
swift build "${BUILD_ARGS[@]}"
BIN_DIR="$(swift build "${BUILD_ARGS[@]}" --show-bin-path)"

APP="build/$APP_NAME.app"
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"
cp "$BIN_DIR/MacSpaceTidyApp" "$APP/Contents/MacOS/$APP_NAME"
# The core reads the catalog from the app's Resources folder (see Catalog.loadBundled).
cp "Sources/MacSpaceTidyCore/Resources/catalog.json" "$APP/Contents/Resources/"
# Generated by scripts/make-icon.swift.
cp "Assets/AppIcon.icns" "$APP/Contents/Resources/"

cat > "$APP/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleName</key><string>$APP_NAME</string>
    <key>CFBundleDisplayName</key><string>$APP_NAME</string>
    <key>CFBundleIdentifier</key><string>$BUNDLE_ID</string>
    <key>CFBundleExecutable</key><string>$APP_NAME</string>
    <key>CFBundlePackageType</key><string>APPL</string>
    <key>CFBundleIconFile</key><string>AppIcon</string>
    <key>CFBundleShortVersionString</key><string>$VERSION</string>
    <key>CFBundleVersion</key><string>$VERSION</string>
    <key>LSMinimumSystemVersion</key><string>$MIN_MACOS</string>
    <key>NSHighResolutionCapable</key><true/>
</dict>
</plist>
PLIST

codesign --force --sign - "$APP"
printf 'Built %s\n' "$APP"
